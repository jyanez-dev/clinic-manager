    tel1 varchar(20),
    tel2 varchar(20),
    mobile1 varchar(20),
    mobile2 varchar(20),
    email varchar(100),
    observation varchar(1025),
    status boolean DEFAULT true,
    create_user integer,
    create_date timestamp DEFAULT CURRENT_TIMESTAMP,
    edit_user integer,
    edit_date timestamp,
    CONSTRAINT pk_patients PRIMARY KEY (patient_id)
);

CREATE TABLE employees (
