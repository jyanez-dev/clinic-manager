CREATE TABLE appointments (
    appointment_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    patient_id integer NOT NULL,
    employee_id integer NOT NULL,
    appointment_date_time timestamp,
    appointment_status_id integer DEFAULT 1,
    observation varchar(1025),
    description varchar(1025),
    amount numeric(16,4),
    create_user integer,
    create_date timestamp DEFAULT CURRENT_TIMESTAMP,
    edit_user integer,
    edit_date timestamp,
    CONSTRAINT pk_appointments PRIMARY KEY (appointment_id)
);

CREATE TABLE medical_records (
    medical_record_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    appointment_id integer NOT NULL,
    chief_complaint text,
    diagnosis text,
    treatment text,
    prescription text,
    observation text,
    recommendations text,
    create_user integer,
    create_date timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
    edit_user integer,
    edit_date timestamp,
    CONSTRAINT pk_medical_records PRIMARY KEY (medical_record_id),
    CONSTRAINT fk_medical_records_appointments
        FOREIGN KEY (appointment_id)
        REFERENCES appointments (appointment_id)
);

