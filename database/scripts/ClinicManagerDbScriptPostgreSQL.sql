    name varchar(20) NOT NULL,
    CONSTRAINT pk_appointment_status PRIMARY KEY (appointment_status_id)
);

CREATE TABLE document_types (
    doc_type_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    name varchar(20) NOT NULL,
    CONSTRAINT pk_document_types PRIMARY KEY (doc_type_id)
);

CREATE TABLE positions (
    position_id integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,
